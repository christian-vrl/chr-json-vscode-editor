// Times plain jsonrepair and both engines on generated commented files (002 T11 spike). Writes
// bench.md. `node bench.ts`; engine D is skipped where an earlier run took minutes.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { jsonrepair } from 'jsonrepair';
import { ENGINES } from './engines.ts';

/** About `mb` MB of commented objects, one missing comma per 5000 items, quotes `q`. */
function commented(mb: number, q: string): string {
  const items: string[] = [];
  for (let i = 0, len = 0; len < mb * 1e6; i++) {
    const s = `  // item ${i}\n  {"id": ${i}, "name": ${q}n${i}${q}, "tags": [${q}a${q}, ${q}b${q}]}${i % 5000 === 7 ? '' : ','} /* t${i} */`;
    items.push(s);
    len += s.length + 1;
  }
  return '[\n' + items.join('\n') + '\n]\n';
}

const time = (f: () => unknown): number => {
  const t0 = performance.now();
  f();
  return performance.now() - t0;
};

const runs: [number, string, string[]][] = [
  [1, '"', ['T', 'D']],
  [10, '"', ['T', 'D']],
  [50, '"', ['T']],
  [0.01, "'", ['T', 'D']],
  [1, "'", ['T']],
  [10, "'", ['T']],
];
const lines = [
  '# 002 T11 timings (generated by `bench.ts`; do not edit)',
  '',
  `${os.cpus()[0]?.model ?? 'unknown CPU'}, ${os.cpus().length} cores, Node ${process.version}, ${new Date().toISOString().slice(0, 10)}. One run each, wall clock.`,
  "Files are arrays of commented objects with one missing comma per 5000 items. With `'` quotes every string needs a quote change, the worst case for engine D's diff.",
  '',
  '| Size | Quotes | Comments | jsonrepair | Engine T | Engine D |',
  '|---|---|---|---|---|---|',
];
for (const [mb, q, engines] of runs) {
  const text = commented(mb, q);
  const comments = (text.match(/\/\/ item|\/\* t/g) ?? []).length;
  const cell = (key: string) =>
    engines.includes(key) ? `${time(() => ENGINES[key]!.repair(text)).toFixed(0)} ms` : 'skipped';
  const row = `| ${mb} MB | \`${q}\` | ${comments} | ${time(() => jsonrepair(text)).toFixed(0)} ms | ${cell('T')} | ${cell('D')} |`;
  console.log(row);
  lines.push(row);
}
fs.writeFileSync(path.join(import.meta.dirname, 'bench.md'), lines.join('\n') + '\n');
