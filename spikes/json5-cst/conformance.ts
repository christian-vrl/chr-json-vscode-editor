// Supporting evidence, not part of UNK-012's count: runs each option's parser over the official
// json5-tests corpus (https://github.com/json5/json5-tests, MIT). `.json` and `.json5` files must
// parse; `.js` and `.txt` files must be rejected. Files under todo/ are skipped, as upstream does.
// Usage: pnpm --filter @chr-json-editor/spike-json5-cst conformance <path to a json5-tests checkout>
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { option as A } from './options/jsonc-parser.ts';
import { option as B } from './options/json5.ts';
import { option as C } from './options/momoa.ts';
import { option as D } from './options/jsonc-eslint-parser.ts';
import { engineOption as E } from './options/croct.ts';
import { option as F } from './options/own.ts';

const corpus = process.argv[2];
if (!corpus) throw new Error('usage: conformance.ts <json5-tests dir>');
const here = path.dirname(fileURLToPath(import.meta.url));
const sha = execFileSync('git', ['-C', corpus, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();

const files: string[] = [];
for (const dir of fs.readdirSync(corpus).sort()) {
  if (dir === 'todo' || dir.startsWith('.') || !fs.statSync(path.join(corpus, dir)).isDirectory())
    continue;
  for (const f of fs.readdirSync(path.join(corpus, dir)).sort()) {
    if (/\.(json|json5|js|txt)$/.test(f)) files.push(`${dir}/${f}`);
  }
}

const lines = [
  `<!-- Generated by conformance.ts on Node ${process.version} from json5-tests @ ${sha}; do not edit by hand. -->`,
  '',
  `| Option | Correct (of ${files.length}) | Wrongly rejected valid | Wrongly accepted invalid |`,
  '|---|---|---|---|',
];
const misses: string[] = [];
for (const o of [A, B, C, D, E, F]) {
  const parse = o.parse!;
  const rejected: string[] = [];
  const accepted: string[] = [];
  for (const f of files) {
    const valid = /\.json5?$/.test(f);
    let ok = true;
    try {
      parse(fs.readFileSync(path.join(corpus, f), 'utf8'));
    } catch {
      ok = false;
    }
    if (valid && !ok) rejected.push(f);
    if (!valid && ok) accepted.push(f);
  }
  const correct = files.length - rejected.length - accepted.length;
  lines.push(`| ${o.id} ${o.name} | **${correct}** | ${rejected.length} | ${accepted.length} |`);
  misses.push(
    `- **${o.id}:** ${rejected.length + accepted.length === 0 ? 'none' : [...rejected.map((f) => `rejects \`${f}\``), ...accepted.map((f) => `accepts \`${f}\``)].join(', ')}`,
  );
}
lines.push('', '### Misses', '', ...misses, '');
fs.writeFileSync(path.join(here, 'conformance.md'), lines.join('\n'));
console.log(lines.slice(2, 10).join('\n'));
