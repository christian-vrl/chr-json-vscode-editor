// Runs every UNK-012 option over the 20 cases in cases/ and writes results.json and results.md.
// Usage: pnpm --filter @chr-json-editor/spike-json5-cst spike
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { PatchOp } from './engine.ts';
import { option as A } from './options/jsonc-parser.ts';
import { option as B } from './options/json5.ts';
import { option as C } from './options/momoa.ts';
import { option as D } from './options/jsonc-eslint-parser.ts';
import { engineOption as E, nativeOption as E2 } from './options/croct.ts';
import { option as F } from './options/own.ts';
import type { Option } from './options/option.ts';

const here = path.dirname(fileURLToPath(import.meta.url));
const casesDir = path.join(here, 'cases');
const options: Option[] = [A, B, C, D, E, E2, F];

interface Outcome {
  pass: boolean;
  why?: string;
}

/** First differing line, shown with escapes, so a failure says what went wrong. */
function firstDiff(got: string, want: string): string {
  let i = 0;
  while (i < got.length && got[i] === want[i]) i++;
  const lineStart = Math.max(want.lastIndexOf('\n', i - 1), got.lastIndexOf('\n', i - 1)) + 1;
  const line = (s: string) => {
    const end = s.indexOf('\n', i);
    const shown = JSON.stringify(s.slice(lineStart, end < 0 ? undefined : end));
    return shown.replace(/[^\x20-\x7e]/gu, (c) => `\\u{${c.codePointAt(0)!.toString(16)}}`);
  };
  return `differs at offset ${i}: got ${line(got)}, want ${line(want)}`;
}

/** Package dir of an installed dependency, resolved the way Node does: nearest node_modules upward. */
function packageDir(name: string, from: string): string {
  for (let dir = from; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name, 'package.json');
    if (fs.existsSync(candidate)) return fs.realpathSync(path.dirname(candidate));
    if (path.dirname(dir) === dir) throw new Error(`${name} not installed`);
  }
}

/** Transitive production dependency tree: name@version → license. */
function depTree(
  names: string[],
  from: string,
  seen = new Map<string, string>(),
): Map<string, string> {
  for (const name of names) {
    const dir = packageDir(name, from);
    const pj = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')) as {
      version: string;
      license: string;
      dependencies?: Record<string, string>;
    };
    const id = `${name}@${pj.version}`;
    if (seen.has(id)) continue;
    seen.set(id, pj.license);
    depTree(Object.keys(pj.dependencies ?? {}), dir, seen);
  }
  return seen;
}

const cases = fs
  .readdirSync(casesDir)
  .filter((d) => /^\d\d-/.test(d))
  .sort();
const read = (c: string, f: string) => fs.readFileSync(path.join(casesDir, c, f), 'utf8');

const results = options.map((o) => {
  const outcomes: Record<string, Outcome> = {};
  for (const c of cases) {
    const input = read(c, 'input.json5');
    const want = read(c, 'expected.json5');
    const ops = JSON.parse(read(c, 'patch.json')) as PatchOp[];
    try {
      const got = o.apply(input, ops);
      outcomes[c] = got === want ? { pass: true } : { pass: false, why: firstDiff(got, want) };
    } catch (e) {
      outcomes[c] = { pass: false, why: `threw: ${(e as Error).message.split('\n')[0]}` };
    }
  }
  const deps = depTree(o.packages, here);
  return {
    id: o.id,
    name: o.name,
    via: o.via,
    passed: Object.values(outcomes).filter((r) => r.pass).length,
    runtimePackages: [...deps].map(([id, license]) => `${id} (${license})`),
    outcomes,
  };
});

const md: string[] = [
  `<!-- Generated by run.ts on Node ${process.version}; do not edit by hand. -->`,
  '',
  `| Option | Edits via | Passed (of ${cases.length}) | Runtime packages added |`,
  '|---|---|---|---|',
  ...results.map(
    (r) =>
      `| ${r.id} ${r.name} | ${r.via} | **${r.passed}** | ${r.runtimePackages.length} ${r.runtimePackages.length ? `(${r.runtimePackages.join(', ')})` : ''} |`,
  ),
  '',
  `| Case | ${results.map((r) => r.id).join(' | ')} |`,
  `|---|${results.map(() => '---').join('|')}|`,
  ...cases.map(
    (c) => `| ${c} | ${results.map((r) => (r.outcomes[c]!.pass ? 'pass' : 'FAIL')).join(' | ')} |`,
  ),
  '',
  '### Failure reasons',
  '',
  ...results.flatMap((r) => {
    const fails = Object.entries(r.outcomes).filter(([, o]) => !o.pass);
    if (fails.length === 0) return [`- **${r.id}:** none`];
    return [
      `- **${r.id}:**`,
      ...fails.map(([c, o]) => `  - \`${c}\`: ${o.why!.replace(/\|/g, '\\|')}`),
    ];
  }),
  '',
];

fs.writeFileSync(path.join(here, 'results.json'), JSON.stringify(results, null, 2) + '\n');
fs.writeFileSync(path.join(here, 'results.md'), md.join('\n'));
for (const r of results)
  console.log(`${r.id.padEnd(3)} ${String(r.passed).padStart(2)}/${cases.length}  ${r.name}`);
